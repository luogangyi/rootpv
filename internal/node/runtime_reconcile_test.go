func TestReconcileRuntimeAdaptersClonesUnknownVendorHandler(t *testing.T) {
	fixture := prepareVendorRuntimeReconcileFixture(t)
	result, err := ReconcileRuntimeAdapters(fixture.configPath, fixture.catalog, fixture.options)
	if err != nil {
		t.Fatalf("ReconcileRuntimeAdapters: %v", err)
	}
	if result.Readiness["vendor-gpu-runc-v2"] == "" {
		t.Fatalf("missing readiness: %#v", result)
	}
	runtimeMap := decodeRuntimeMap(t, fixture.configPath)
	assertVendorRuntimeClone(t, fixture, runtimeMap)
	assertGeneratedRuntimeRegistry(t, fixture.registryPath)
}

type vendorRuntimeReconcileFixture struct {
	root         string
	configPath   string
	registryPath string
	catalog      config.RuntimeCatalog
	options      RuntimeReconcileOptions
}

func prepareVendorRuntimeReconcileFixture(t *testing.T) vendorRuntimeReconcileFixture {
	t.Helper()
	root := t.TempDir()
	writeExecutable(t, root, "opt/vendor/bin/runtime")
	writeExecutable(t, root, "usr/local/bin/rootfs-runtime-wrapper")
	configPath := filepath.Join(root, "etc/containerd/config.toml")
	if err := os.MkdirAll(filepath.Dir(configPath), 0o755); err != nil {
		t.Fatal(err)
	}
	legacyAnnotation := "rootpv" + ".io/*"
	if err := os.WriteFile(configPath, []byte(`
[plugins.'io.containerd.cri.v1.runtime'.containerd.runtimes.vendor-gpu]
  runtime_type = "io.containerd.runc.v2"
[plugins.'io.containerd.cri.v1.runtime'.containerd.runtimes.vendor-gpu.options]
  BinaryName = "/opt/vendor/bin/runtime"
  SystemdCgroup = true
  VendorSwitch = "keep-me"

# Legacy handlers were generated by the pre-catalog configurator.  They must
# be removed during cutover so their obsolete annotation allowlist cannot
# remain active beside the catalog-generated handler.
[plugins.'io.containerd.cri.v1.runtime'.containerd.runtimes.persistent-rootfs-nvidia]
  runtime_type = "io.containerd.runc.v2"
  pod_annotations = ["`+legacyAnnotation+`"]
[plugins.'io.containerd.cri.v1.runtime'.containerd.runtimes.persistent-rootfs-nvidia.options]
  BinaryName = "/usr/local/bin/rootfs-runtime-wrapper-nvidia"
`), 0o644); err != nil {
		t.Fatal(err)
	}
	catalog := config.RuntimeCatalog{FormatVersion: config.RuntimeCatalogFormatVersion, Generation: 7, Adapters: []config.CatalogRuntimeAdapter{{ID: "vendor-gpu-runc-v2", SourceHandler: "vendor-gpu", RuntimeType: config.RuncV2RuntimeType, RootfsHandler: "persistent-rootfs-vendor-gpu-runc-v2", ClusterDigest: "sha256:catalog"}}}
	registryPath := filepath.Join(root, "etc/rootpv/rootpv-runtime-adapters.yaml")
	return vendorRuntimeReconcileFixture{
		root: root, configPath: configPath, registryPath: registryPath, catalog: catalog,
		options: RuntimeReconcileOptions{HostRoot: root, WrapperBinary: "/usr/local/bin/rootfs-runtime-wrapper", RegistryPath: registryPath},
	}
}

func decodeRuntimeMap(t *testing.T, configPath string) map[string]any {
	return decodeRuntimeMapPlugin(t, configPath, "io.containerd.cri.v1.runtime")
}

// decodeRuntimeMapPlugin decodes the runtimes table of the given CRI runtime
// plugin, including the legacy io.containerd.grpc.v1.cri used by config v2.
func decodeRuntimeMapPlugin(t *testing.T, configPath, plugin string) map[string]any {
	t.Helper()
	var raw map[string]any
	_, err := toml.DecodeFile(configPath, &raw)
	requireNoError(t, err, "decode containerd config")
	plugins, ok := raw["plugins"]
	if !ok {
		t.Fatal("containerd config is missing plugins")
	}
	criRuntime := mapValue(plugins)[plugin]
	containerd := mapValue(criRuntime)["containerd"]
	runtimes := mapValue(containerd)["runtimes"]
	return mapValue(runtimes)
}

func assertVendorRuntimeClone(t *testing.T, fixture vendorRuntimeReconcileFixture, runtimeMap map[string]any) {
	t.Helper()
	source := mapValue(runtimeMap["vendor-gpu"])
	shadow := mapValue(runtimeMap["persistent-rootfs-vendor-gpu-runc-v2"])
	if _, exists := runtimeMap["persistent-rootfs-nvidia"]; exists {
		t.Fatalf("legacy handler was not removed: %#v", runtimeMap["persistent-rootfs-nvidia"])
	}
	if stringValue(mapValue(source["options"])["BinaryName"]) != "/opt/vendor/bin/runtime" {
		t.Fatalf("source handler mutated: %#v", source)
	}
	options := mapValue(shadow["options"])
	generatedWrapper := "/usr/local/bin/rootfs-runtime-wrapper-vendor-gpu-runc-v2"
	if stringValue(options["BinaryName"]) != generatedWrapper || options["VendorSwitch"] != "keep-me" || options["SystemdCgroup"] != true {
		t.Fatalf("vendor options were not cloned: %#v", options)
	}
	if target, err := os.Readlink(filepath.Join(fixture.root, generatedWrapper)); err != nil || target != "rootfs-runtime-wrapper" {
		t.Fatalf("generated wrapper alias: target=%q err=%v", target, err)
	}
	if !strings.Contains(strings.Join(stringSlice(shadow["pod_annotations"]), ","), "openfuyao.cn/*") || !strings.Contains(strings.Join(stringSlice(shadow["container_annotations"]), ","), "openfuyao.cn/*") {
		t.Fatalf("RootPV annotations are not propagated to OCI: %#v", shadow)
	}
}

func assertGeneratedRuntimeRegistry(t *testing.T, registryPath string) {
	t.Helper()
	registry, err := os.ReadFile(registryPath)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(registry), "formatVersion: rootpv-runtime-adapters-v2") || !strings.Contains(string(registry), "delegateBinary: /opt/vendor/bin/runtime") {
		t.Fatalf("unexpected registry: %s", registry)
	}
	info, err := os.Stat(registryPath)
	if err != nil || info.Mode().Perm() != 0o600 {
		t.Fatalf("registry must be root-owned mode 0600: info=%#v err=%v", info, err)
	}
}

func stringSlice(value any) []string {
	switch values := value.(type) {
	case []string:
		return values
	case []any:
		result := make([]string, 0, len(values))
		for _, value := range values {
			if stringValue(value) != "" {
				result = append(result, stringValue(value))
			}
		}
		return result
	default:
		return nil
	}
}
