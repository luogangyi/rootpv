package node

import (
	"context"
	"time"
)

// RunPeriodically 立即执行一次任务，并在指定周期内持续执行直到上下文取消。
func RunPeriodically(ctx context.Context, interval time.Duration, run func()) {
	run()
	go func() {
		ticker := time.NewTicker(interval)
		defer ticker.Stop()
		for {
			select {
			case <-ctx.Done():
				return
			case <-ticker.C:
				run()
			}
		}
	}()
}
